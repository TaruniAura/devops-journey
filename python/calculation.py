def add(a,b):
    return a+b
def subtract(a,b):
    return a - b
def multiply(a,b):
    return a*b
def divide(a,b):
    return a/b

a=int(input("Enter first number: "))
b=int(input("Enter second number: "))
r1=add(a,b)
r2=subtract(a,b)
r3=multiply(a,b)
r4=divide(a,b)
print("Addition:",r1)
print("Subtraction:",r2)
print("Multiplication:",r3)
print("Division:",r4)

